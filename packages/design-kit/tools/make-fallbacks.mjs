// Measures each web font against the phone's built-in font and writes
// fonts/fallbacks.css: a stand-in font scaled to take exactly the same space,
// so nothing jumps when the real font arrives (no layout shift).
// Run after fetch-fonts.mjs: node tools/make-fallbacks.mjs
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const fonts = join(dirname(fileURLToPath(import.meta.url)), '../fonts');
const FAMILIES = [
  ['Cormorant Garamond', 'cormorant-garamond-normal.woff2', 'serif'],
  ['Jost', 'jost-normal.woff2', 'sans'],
  ['Bricolage Grotesque', 'bricolage-grotesque-normal.woff2', 'sans'],
  ['DM Sans', 'dm-sans-normal.woff2', 'sans'],
  ['Syne', 'syne-normal.woff2', 'sans'],
  ['Manrope', 'manrope-normal.woff2', 'sans'],
  ['Fraunces', 'fraunces-normal.woff2', 'serif'],
  ['Work Sans', 'work-sans-normal.woff2', 'sans'],
];
// Built-in fonts that share Arial's / Times New Roman's measurements on most devices.
const LOCAL = { sans: ["local('Arial')", "local('Helvetica')", "local('Liberation Sans')", "local('Roboto')"], serif: ["local('Times New Roman')", "local('Times')", "local('Liberation Serif')", "local('Noto Serif')"] };
const SAMPLE = 'The quick brown fox jumps over the lazy dog. Sweets made fresh every morning, 1962 – ₹1,25,000';

const browser = await chromium.launch();
const page = await browser.newPage();
let css = '/* Size-matched stand-ins for each web font (generated by tools/make-fallbacks.mjs). */\n';
for (const [family, file, kind] of FAMILIES) {
  const data = readFileSync(join(fonts, file)).toString('base64');
  const m = await page.evaluate(async ({ family, data, local, sample }) => {
    const face = new FontFace(`M-${family}`, `url(data:font/woff2;base64,${data})`, { weight: '400' });
    document.fonts.add(await face.load());
    const fb = new FontFace(`FB-${family}`, local.join(', '));
    document.fonts.add(await fb.load());
    const c = document.createElement('canvas').getContext('2d');
    const measure = (f) => { c.font = `400 100px ${f}`; const t = c.measureText(sample); return { w: t.width, a: t.fontBoundingBoxAscent, d: t.fontBoundingBoxDescent }; };
    return { web: measure(`'M-${family}'`), fb: measure(`'FB-${family}'`) };
  }, { family, data, local: LOCAL[kind], sample: SAMPLE });
  const size = m.web.w / m.fb.w;
  const pct = (v) => `${(v * 100).toFixed(2)}%`;
  css += `@font-face{font-family:'${family} Fallback';src:${LOCAL[kind].join(',')};size-adjust:${pct(size)};ascent-override:${pct(m.web.a / 100 / size)};descent-override:${pct(m.web.d / 100 / size)};line-gap-override:0%}\n`;
  console.log(`✓ ${family}: size ${pct(size)}`);
}
await browser.close();
writeFileSync(join(fonts, 'fallbacks.css'), css);
